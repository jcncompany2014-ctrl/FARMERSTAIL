/**
 * PostgREST `.or()` 문자열에 사용자 입력을 넣기 전 정화 — 정본 한 곳.
 *
 * # 왜 필요한가 (2026-08-08 보안 재감사)
 * supabase-js 는 `.ilike(col, value)` 의 **값 인자만** escape 한다.
 * `.or('email.ilike.%x%,name.ilike.%x%')` 는 **표현식 문자열**이라 그대로
 * 파서에 들어간다. 즉 사용자 입력에 `,` `(` `)` `.` 가 있으면 **필터 절이
 * 주입**된다.
 *
 * 저장소가 이미 다섯 곳에서 escape 를 하고 있었는데 **두 곳만 빠져** 있었다:
 *   · `app/admin/users/page.tsx` — 완전 미escape
 *   · `app/admin/search-all/page.tsx` — `%`·`_`(LIKE 와일드카드)만 처리하고
 *     PostgREST 문법 토큰은 안 막음
 * 그리고 다섯 곳의 방식도 서로 조금씩 달랐다(어떤 곳은 백슬래시 이스케이프,
 * 어떤 곳은 문자 제거). 같은 규칙이 흩어지면 갈라진다 — 이 저장소에서 여러 번
 * 확인한 형태다.
 *
 * # 피해 범위
 * RLS·컬럼 권한은 뚫리지 않는다. 실제 피해는 "어드민이 잘못된 목록을 보고
 * 판단한다" + PostgREST 파싱 오류(500)다. 데이터 유출은 아니지만, 어드민에게
 * 링크 하나를 열게 하면 되는 벡터라 막아 둔다.
 *
 * # 방식 — 제거(strip)
 * 백슬래시 이스케이프는 PostgREST 버전에 따라 해석이 갈린 전례가 있다.
 * 검색어에서 문법 토큰을 **빼 버리는** 쪽이 결과가 예측 가능하고, 검색 품질
 * 손실도 사실상 없다(이름·이메일·전화에 `,()` 를 넣어 찾는 사람은 없다).
 */

/**
 * PostgREST or() **문법** 토큰 — 이것들만 필터 절 주입에 쓰인다.
 *
 * ★`.` `_` `%` `:` 는 지우지 않는다 (2026-08-08 diff 재검증에서 잡힘).
 * 처음엔 넓게 지웠는데, `.` 을 지우니 **이메일 검색이 항상 0건**이 됐다
 * (`hello@x.com` → `hello@xcom`). CS 의 가장 흔한 동선이 어드민 회원 검색에
 * 이메일을 붙여넣는 것이다. or() 표현식에서 위험한 건 절을 가르는 `,` 와
 * 괄호·따옴표·백슬래시뿐이고, **value 위치의 `.` 은 무해하다.**
 * LIKE 와일드카드(`%` `_`)는 제거 대신 escape 한다 — 지우면 언더스코어가
 * 든 이메일(`a_b@x.com`)도 못 찾는다.
 */
const SYNTAX_TOKENS = /[,()"'\\]/g
const LIKE_WILDCARDS = /[%_]/g

/**
 * `.or()` 안에 넣을 검색어를 정화한다.
 *
 * @param raw 사용자가 입력한 검색어
 * @param maxLen 잘라낼 길이(기본 80) — 긴 입력이 파서를 흔들지 않게
 * @returns 정화된 문자열. **빈 문자열이면 검색을 걸지 말 것**(전체 조회가
 *          되지 않도록 호출부가 판단한다).
 */
export function safeOrTerm(raw: string, maxLen = 80): string {
  return raw
    .replace(SYNTAX_TOKENS, '')
    .replace(LIKE_WILDCARDS, (m) => `\\${m}`)
    .trim()
    .slice(0, maxLen)
}
