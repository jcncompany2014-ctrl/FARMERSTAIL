/**
 * 주요 재료 5줄 — 주단백질 · 내장 · 토핑 · 채소·곡물 · 오일·보충. 이름은 전부 정본(RECIPE_INGREDIENTS)에서 읽는다.
 * 채소·곡물과 오일·보충은 4종 공통이라 대표 둘만 보이고(전체는 바로 아래 '전체 원재료'), 정본에서 빠지면 여기서도 빠진다.
 * 토핑 첫째(hero)는 4종이 전부 달라서 "이 레시피에만" 이 참이다 — 둘째(support)는 겹칠 수 있어(블루베리 = 치킨·한우) 말하지 않는다.
 */
export function recipeLedger(p: Protein): LedgerRow[] {
  const ing = RECIPE_INGREDIENTS[SKU_MODEL[p].legacyLine]
  if (!ing) throw new Error(`원재료가 없는 레시피: ${p}`)
  const organs = ing.organs.map((o) => o.replace(/^(닭|오리|흑돼지|한우)/, ''))
  const [hero, support] = ing.toppings
  const veg = ing.veg.filter((v) => v === '당근' || v === '현미')
  const base = ing.base
    .filter((b) => b === '연어유' || b.includes('뉴트리 코어'))
    .map((b) => (b.includes('뉴트리 코어') ? '뉴트리 코어' : b))
  return [
    { label: '주단백질', name: ing.main, note: MAIN_NOTE[p] },
    {
      label: '내장',
      name: organs.join(' · '),
      note: `${p === 'duck' ? '내장도 오리예요. ' : ''}간은 철분과 비타민A를, 염통은 자연 타우린을 원물 그대로 채워요.`,
    },
    { label: '토핑', name: `${hero} · ${support}`, note: `${eunNeun(hero)} ${SHORT_NAME[p]} 레시피에만 들어가요.` },
    { label: '채소·곡물', name: veg.join(' · '), note: '현미는 천천히 소화되는 통곡물이에요. 4종 모두에 들어가요.' },
    { label: '오일·보충', name: base.join(' · '), note: '오메가-3를 채우는 오일과, 원물로 못 채운 비타민·미네랄만 메우는 전용 믹스예요.' },
  ]
}

