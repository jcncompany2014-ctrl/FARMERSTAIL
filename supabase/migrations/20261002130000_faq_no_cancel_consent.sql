-- 2026-10-02 FAQ — 결제 후 취소 제한(결제 전 별도 동의 박스)과 맞춘다 (사장님 A안 · "바로 해도 돼").
--
-- 환불정책·약관을 같은 날 개정했다(app/legal/refund 2·3·7항, terms 제7·9조). FAQ 두 행이 "수령 후 7일 미개봉
-- 단순 변심 환불"을 조건 없이 약속하고 있었다 → 결제 전에 '결제 후 취소 안내'에 동의한 정기배송 박스는 예외라고
-- 범위를 정확히 쓴다(동의 기록이 없는 박스는 7일 환불 그대로 — 고객에게 불리하게 넓히지 않는다).
-- 행을 못 찾거나 문장이 바뀌어 있으면 실패시킨다(0행 갱신이 성공으로 지나가지 않게).

do $$
declare n int;
begin
  update public.faqs
     set answer = '정기배송 박스는 결제 전에 ''결제 후 취소 안내''에 동의하셨다면, 결제 후에는 우리 아이 몫으로 맞춤 조리해 보내드려서 단순 변심으로는 취소·환불이 어려워요. 다음 박스는 결제 전까지 정기배송 화면에서 미루거나 해지할 수 있어요. 그 밖의 경우 단순 변심은 수령 후 7일 이내, 미개봉 상태일 때 가능합니다. 받은 박스에 파손·변질 같은 문제가 있으면 환불해 드려요. 혹시 아이 입맛에 맞지 않을까 걱정되신다면 화식 비율을 낮은 단계(곁들임)로 시작해 반응을 보며 늘려가는 방법을 추천드려요.'
   where question = '환불은 언제까지 가능한가요?'
     and answer like '단순 변심은 수령 후 7일 이내, 미개봉 상태일 때 가능합니다.%';
  get diagnostics n = row_count;
  if n <> 1 then raise exception 'faq 환불은 언제까지 가능한가요? 갱신 행 수 %', n; end if;

  update public.faqs
     set answer = replace(answer,
       '미개봉 상태라면 수령 7일 이내 단순 변심 환불이 가능합니다.',
       '결제 전에 ''결제 후 취소 안내''에 동의하신 정기배송 박스는 우리 아이 몫으로 맞춤 조리한 박스라 단순 변심 환불이 어렵고, 그 밖의 경우 미개봉 상태라면 수령 7일 이내 단순 변심 환불이 가능합니다.')
   where question = '우리 아이가 잘 안 먹어요. 환불 가능한가요?'
     and answer like '%미개봉 상태라면 수령 7일 이내 단순 변심 환불이 가능합니다.%';
  get diagnostics n = row_count;
  if n <> 1 then raise exception 'faq 우리 아이가 잘 안 먹어요 갱신 행 수 %', n; end if;
end $$;
