--    "제조일로부터 냉동 180일·해동 후 냉장 3일 이내·재냉동 금지". 식품 안전이라 라벨 기준으로.
-- ② 알레르기: "원료가 든 레시피는 자동 제외, 실수로 섞일 일 없다" — 연어유·난각분말은 4종 공통이라 생선·계란은
--    제외되지 않는다. 사실대로 + 근거(주재료 단백질이 아니라 가능성 매우 낮음) + 카카오톡 문의 안내.
--    근거: Mueller·Olivry·Prélaud 2016 BMC Vet Res 12:9 (개 음식 알레르기원 = 소·유제품·닭·밀),
--    Mark et al. 2008 Allergy Asthma Proc 29:528 (생선 알레르기 환자 6/6 이 어유 보충제에 무반응),
--    Urisu et al. 2015 Chem Immunol Allergy 101:124 (달걀 알레르기원 = 흰자·노른자 단백질).
-- ③ 블로그: 없는 '관절 케어 SKU 글루코사민·콘드로이틴 권장량 100%' · 급여 열량 '체중 1kg당 25-40kcal'
--    (5kg=125-200kcal — 쉬는 동안 쓰는 에너지 234kcal 보다도 낮다) → 앱과 같은 계산식으로.
-- 각 문장은 정확히 한 번 바뀌어야 한다 — 아니면 전부 되돌린다(원문이 바뀌어 있으면 사람이 봐야 함).
