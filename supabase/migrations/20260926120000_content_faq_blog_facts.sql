do $$
declare
  n int;
  v text;
begin
  -- ① 보관·해동
  update public.faqs
     set question = '보관·해동은 어떻게 하나요?',
         answer = E'파머스테일 화식은 모두 냉동으로 보내드려요. 받으시면 바로 냉동실(-18℃ 이하)에 넣어 주세요. 봉투에 적힌 유통기한(제조일로부터 냉동 180일)까지 보관할 수 있어요.\n\n먹이기 전날, 그날 필요한 만큼만 냉장실로 옮겨 천천히 해동해 주세요. 해동한 뒤에는 냉장 보관하고 3일 안에 먹이고, 다시 얼리지 마세요. 한 번에 2~3일치만 해동하는 걸 권해요.',
         updated_at = now()
   where id = '6337dfb7-f498-4e89-80fc-365bd38be950' and answer like '%12개월%';
  get diagnostics n = row_count;
  if n <> 1 then raise exception 'faq 보관 행 갱신 %건(1이어야 함)', n; end if;

  update public.faqs
     set answer = replace(answer, '(냉동은 제조일로부터 12개월, 냉장은 14일 이내 발송이 원칙이에요.)', '(봉투의 유통기한은 제조일로부터 냉동 180일이에요.)'),
         updated_at = now()
   where id = '844e439b-bd29-4084-aaba-75cae4025b07'
     and answer like '%(냉동은 제조일로부터 12개월, 냉장은 14일 이내 발송이 원칙이에요.)%';
  get diagnostics n = row_count;
  if n <> 1 then raise exception 'faq 유통기한 행 갱신 %건', n; end if;

  -- ② 알레르기
  update public.faqs
     set answer = E'안심하고 알려주세요. 2분 설문에서 닭·오리·돼지·소 가운데 못 먹는 단백질을 고르면, 그 단백질이 들어간 레시피는 우리 아이 박스 구성에서 자동으로 빠져요.\n\n다만 연어유(오메가-3)와 난각분말(칼슘)은 네 가지 레시피에 모두 아주 조금씩 들어가요. 반려견의 음식 알레르기는 대부분 소고기·유제품·닭고기·밀처럼 주재료 단백질에 대한 반응으로 보고돼 있어요. 연어유는 단백질이 거의 없는 기름이고, 난각분말은 알레르기를 일으키는 흰자·노른자가 아닌 달걀 껍데기에서 얻은 칼슘이라, 알레르기를 일으킬 가능성은 매우 낮다고 알려져 있어요.\n\n그래도 생선이나 달걀 알레르기를 진단받았거나 걱정되신다면 카카오톡으로 편하게 문의해 주세요. 우리 아이 상황에 맞게 함께 살펴볼게요. 모든 레시피의 전체 원재료는 봉투 뒷면 원재료표에 그대로 적혀 있어요.',
         updated_at = now()
   where id = '8b94fb80-1fc9-4acb-a3a3-fb09f085af17' and answer like '%실수로 섞여 들어갈 일이 없습니다%';
  get diagnostics n = row_count;
  if n <> 1 then raise exception 'faq 알레르기 행 갱신 %건', n; end if;

  -- ③ 블로그 — 관절 보조제
  select content into v from public.blog_posts where id = '48371f08-7403-418b-8502-2957ae677e97';
  if v not like '%파머스테일 관절 케어 SKU 는 글루코사민·콘드로이틴 권장량 100% + 오메가-3 (EPA+DHA) 보강.%'
     or v not like '%BCS 3/5 유지%'
     or v not like '%갑각류 알러지 (글루코사민이 새우 껍질에서 추출) — 어류 기반 제품 선택%' then
    raise exception '관절 글 원문이 예상과 다르다';
  end if;
  v := replace(v, '파머스테일 관절 케어 SKU 는 글루코사민·콘드로이틴 권장량 100% + 오메가-3 (EPA+DHA) 보강.',
    '참고로 파머스테일 레시피에는 글루코사민·콘드로이틴이 들어 있지 않아요. 네 가지 레시피 모두 연어유로 오메가-3(EPA·DHA)를 채우지만, 관절 보조가 필요한 아이라면 수의사와 상의해 보조제를 따로 함께 쓰는 걸 권해요.');
  v := replace(v, '- **체중 관리** — 가장 효과적. BCS 3/5 유지', '- **체중 관리** — 가장 효과적. 갈비뼈가 손끝에 살짝 만져지는 적정 체중 유지');
  v := replace(v, '- 갑각류 알러지 (글루코사민이 새우 껍질에서 추출) — 어류 기반 제품 선택',
    '- 갑각류 알레르기 (글루코사민은 주로 게·새우 껍질에서 얻어요) — 갑각류 원료가 아닌 제품 선택');
  update public.blog_posts set content = v, updated_at = now() where id = '48371f08-7403-418b-8502-2957ae677e97';

  -- ③ 블로그 — 화식 첫 시작 7가지
  select content into v from public.blog_posts where id = 'cc1ecb4e-5bdb-4767-a762-f7f3d2df28ba';
  if v not like '%체중 1kg당 일일 25-40 kcal (활동량에 따라). 5kg 강아지 = 125-200 kcal/일.%'
     or v not like '%파머스테일 SKU 는 모두%'
     or v not like '%단일 SKU 만 급여해도%'
     or v not like '%SKU 를 바꿔보세요%' then
    raise exception '화식 FAQ 글 원문이 예상과 다르다';
  end if;
  v := replace(v, E'체중 1kg당 일일 25-40 kcal (활동량에 따라). 5kg 강아지 = 125-200 kcal/일.\n\n마이페이지 → 우리 아이 등록하면 자동 계산됩니다.',
    E'강아지에게 필요한 열량은 몸무게에 정비례하지 않아요. 몸이 작을수록 체중 1kg당 필요한 열량이 커서, 수의영양학에서는 쉬는 동안 쓰는 에너지(70 × 체중(kg)^0.75)에 나이·중성화·활동량에 따른 계수를 곱해 계산해요. 예를 들어 실내에서 지내는 중성화한 5kg 성견이라면 하루 약 330kcal 안팎이에요.\n\n화식은 수분이 많아서 같은 열량이라도 사료보다 무게가 2~3배 나가요. 그릇에 담긴 양이 많아 보여도 열량은 사료와 같아요.\n\n파머스테일 앱에 우리 아이를 등록하면 나이·중성화·체형·활동량을 반영해 자동으로 계산하고, 2~4주마다 체중을 기록하면 급여량을 다시 맞춰 드려요.');
  v := replace(v, '파머스테일 SKU 는 모두', '파머스테일 레시피는 모두');
  v := replace(v, '단일 SKU 만 급여해도', '한 가지 레시피만 급여해도');
  v := replace(v, 'SKU 를 바꿔보세요', '다른 레시피로 바꿔보세요');
  if v like '%25-40 kcal%' then raise exception '화식 FAQ 급여량 문단이 안 바뀌었다(줄바꿈 차이?)'; end if;
  update public.blog_posts set content = v, updated_at = now() where id = 'cc1ecb4e-5bdb-4767-a762-f7f3d2df28ba';
end $$;
